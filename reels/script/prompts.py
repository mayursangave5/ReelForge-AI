VERIFY_SYSTEM = """आप एक सख्त हिंदी फैक्ट-चेकर हैं।
हर दावे को दिए गए स्रोत पाठ से मिलाएं। अगर दावा स्रोत में सीधे समर्थित नहीं है तो supported=false रखें।
केवल JSON लौटाएं।"""


def verify_prompt(claims: list[str], article: str) -> str:
    claim_lines = "\n".join(f"- {claim}" for claim in claims)
    return f"""स्रोत पाठ:
\"\"\"
{article}
\"\"\"

इन दावों की जांच करें:
{claim_lines}

JSON लौटाएं:
{{
  "results": [
    {{"claim_hi": "दावा", "supported": true, "reason_hi": "स्रोत में आधार"}}
  ]
}}"""
